function localized(text) {
  if(language==='en') return text;
  const key=text.trim();
  let value=zh[key];
  if(value===undefined && /^\d+(?:\.\d+)?× playback$/.test(key)) value=key.replace('playback','倍速播放');
  if(value===undefined && /^\d+ \/ \d+ solved$/.test(key)) value=key.replace(' solved',' 当轮解决');
  if(value===undefined && /^[−+]?\d+(?:\.\d+)? pp$/.test(key)) value=key.replace(' pp',' 个百分点');
  if(value===undefined && /^\d+(?:\.\d+)? s$/.test(key)) value=key.replace(' s',' 秒');
  return value===undefined ? text : text.replace(key,value);
}
function translate(root=document.body){
  if(!root) return;
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);let node;
  while(node=walker.nextNode()){
    if(node.parentElement?.closest('script,style,[data-no-i18n],#language-toggle')) continue;
    if(!textOriginal.has(node)) textOriginal.set(node,node.nodeValue);
    const value=localized(textOriginal.get(node));
    if(node.nodeValue!==value) node.nodeValue=value;
  }
  const elements=[...(root.nodeType===1?[root]:[]),...root.querySelectorAll('[aria-label],[alt],[data-title]')];
  for(const el of elements){
    if(el.id==='language-toggle')continue;
    if(!attrOriginal.has(el))attrOriginal.set(el,{});
    const values=attrOriginal.get(el);
    for(const name of ['aria-label','alt','data-title']){
      if(!el.hasAttribute(name))continue;
      if(!(name in values))values[name]=el.getAttribute(name);
      el.setAttribute(name,localized(values[name]));
    }
  }
}
